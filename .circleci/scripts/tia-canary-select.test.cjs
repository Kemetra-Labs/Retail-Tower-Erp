// The probe text in the CLI's own format (main analysis job beef6cfa, 2026-11-05).
function probeText({ selected = 2, skipped = SPECS.length - 2, reasons = null, found = true, analysis = false } = {}) {
  const r = reasons ?? [[selected, "test atoms impacted by modified files"], [0, "new test atoms"]];
  return [
    "Discovering...",
    `Discovered ${selected + skipped} test atoms in 793ms`,
    found ? "Found test impact generated by: https://app.circleci.com/pipelines/circleci/X/Y/1034" : "No test impact data found",
    ...r.map(([n, why]) => `- ${n} ${why}`),
    `Selected ${selected} test atoms, Skipped ${skipped} test atoms in 841ms`,
    "Patching test impact data version: 1043",
    ...(analysis ? ["Analyzing 2 test atoms"] : []),
  ].join("\n");
}

// A passing IMPACTED input; each test breaks one thing.
function inputs(over = {}) {
  return {
    sha: SHA,
    expectedSha: SHA,
    guard: { decision: "TIA_ELIGIBLE", source: "guard.json", reason: "ok", head: SHA, mustRun: [MUST] },
    guardChanged: [`${API}src/catalog/x.ts`, `${API}test/a/one.spec.ts`, "services/backend-core/changelog.d/RT-1.md"],
    discoveredText: `${SPECS.join("\n")}\n`,
    selectedText: "test/a/one.spec.ts\ntest/a/two.spec.ts\n",
    listTestsRc: 0,
    probeText: probeText(),
    probeRc: 0,
    textReaders: [],
    ...over,
  };
}

