test("config.yml: the canary is read only inside remote-api-jest, and its FULL path is the default run", () => {
  const cfg = readText(".circleci/config.yml");
  const uses = cfg.match(/<< pipeline\.parameters\.api_tia_canary >>/g) || [];
  assert.equal(uses.length, 2, "api_tia_canary must appear only in remote-api-jest's two step conditions");
  const job = cfg.slice(cfg.indexOf("\n  remote-api-jest:\n"), cfg.indexOf("\n  remote-db-package:\n"));
  assert.equal((job.match(/<< pipeline\.parameters\.api_tia_canary >>/g) || []).length, 2);
  for (const s of ["- remote-guard", "- backend-setup", "- tia-shadow-start", "- tia-canary", "- tia-shadow-report", "path: /tmp/test-reports"]) {
    assert.ok(job.includes(s), `remote-api-jest lost ${s}`);
  }
  const fullRun = "timeout -k 2m 20m node_modules/.bin/jest --forceExit --json --outputFile=/tmp/remote/api-jest.json || rc=$?";
  const canary = cfg.slice(cfg.indexOf("\n  tia-canary:\n"), cfg.indexOf("\njobs:\n"));
  assert.ok(job.includes(fullRun), "the default full run changed");
  assert.ok(canary.includes(fullRun), "the canary FULL fallback is not the default full run");
  assert.match(canary, /--runTestsByPath "\$\{atoms\[@\]\}"/);
  assert.match(canary, /--run-tests=none --analyze-tests=none/);
  assert.match(canary, /TIA_GUARD_RUNTIME=1 timeout 120 node --test ~\/project\/\.circleci\/scripts\/tia-canary-select\.test\.cjs/);
  // RT-921 c15655 item 2: the canary path runs the risk guard and list-tests, never doctor; the
  // default path keeps tia-shadow-start (guard, doctor, list-tests) unchanged.
  const whenBlocks = job.split(/\n {6}- when:\n/).slice(1);
  const defaultBlock = whenBlocks.find((b) => /not: << pipeline\.parameters\.api_tia_canary >>/.test(b));
  const canaryBlock = whenBlocks.find((b) => !/not: /.test(b) && /api_tia_canary/.test(b));
  assert.ok(defaultBlock && canaryBlock, "both when blocks found in remote-api-jest");
  assert.match(defaultBlock, /- tia-shadow-start\n/);
  assert.match(canaryBlock, /- tia-risk-guard\n {12}- tia-fullrun-bypass\n {12}- tia-list-tests\n {12}- tia-canary\n/);
  // RT-921 c15663 option A: the bypass edits only the job's copy; the plan step restores it with
  // git and records the result before it lists or plans anything.
  const bypass = cfg.slice(cfg.indexOf("\n  tia-fullrun-bypass:\n"), cfg.indexOf("\n  # RT-1239 follow-up (RT-921 c15655 item 2)"));
  assert.match(bypass, /tia-canary-select\.cjs bypass --out \/tmp\/tia --suites \.circleci\/test-suites\.yml/);
  assert.match(bypass, /TIA_GUARD_RUNTIME=1 timeout 120 node --test \.circleci\/scripts\/tia-canary-select\.test\.cjs/);
  const planStep = canary.slice(canary.indexOf("TIA canary: plan IMPACTED or FULL"));
  const restoreAt = planStep.indexOf("git -C ~/project checkout -- .circleci/test-suites.yml");
  assert.ok(restoreAt > 0, "the plan step restores the suite file");
  assert.ok(restoreAt < planStep.indexOf("jest --listTests"), "restore before discovery");
  assert.match(planStep, /git -C ~\/project diff --quiet -- \.circleci\/test-suites\.yml \|\| rc=\$\?\n\s+echo "\$rc" > \/tmp\/tia\/fullrun-restore\.rc/);
  // The default (non-canary) path never bypasses.
  assert.doesNotMatch(defaultBlock, /tia-fullrun-bypass/);
  assert.equal((cfg.match(/- tia-fullrun-bypass\n/g) || []).length, 1);
  const listTests = cfg.slice(cfg.indexOf("\n  tia-list-tests:\n"), cfg.indexOf("\n  # RT-1188: the report after the full run"));
  assert.match(listTests, /circleci testsuite list-tests "backend api jest"/);
  assert.doesNotMatch(listTests, /testsuite doctor/);
  assert.doesNotMatch(canary, /testsuite doctor/);
  // The vendor's impacted mode is not used: the must-run specs could not be added to it.
  assert.doesNotMatch(cfg, /--run-tests=impacted/);
  // remote-api-jest stays the only job of remote-dev-api, in the remote-dev serial group.
  assert.match(cfg, /\n {2}remote-dev-api:\n(?: {4}[^\n]*\n|\n)*? {6}- remote-api-jest:\n {10}serial-group: << pipeline\.project\.slug >>\/remote-dev\n/);
});
