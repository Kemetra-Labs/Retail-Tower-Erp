// postgres-container is exempt only because it reads packages/db migrations, which the guard
// forces FULL. If its reads change, this fails, the in-job self-test fails, and the canary is FULL.
test("the exempt helper reads only packages/db migrations", () => {
  assert.deepEqual(sel.EXEMPT_HELPERS, ["test/_helpers/postgres-container.ts"]);
  const src = readText("services/backend-core/apps/api/test/_helpers/postgres-container.ts");
  const calls = [...src.matchAll(/\b(readFileSync|readdirSync|opendirSync|execSync|execFileSync|spawnSync|spawn|exec)\(([^,)]*)/g)].map((m) => `${m[1]}(${m[2].trim()}`);
  assert.deepEqual(calls.sort(), ["readFileSync(UP_SQL_PATH", "readFileSync(resolve(DRIZZLE_DIR", "readdirSync(DRIZZLE_DIR"].sort());
  const dir = /\bDRIZZLE_DIR\s*=\s*([^;]+);/.exec(src);
  assert.ok(dir && /["']packages["'],\s*["']db["'],\s*["']drizzle["']/.test(dir[1]), `DRIZZLE_DIR must point into packages/db/drizzle: ${dir && dir[1]}`);
  assert.match(src, /\bUP_SQL_PATH\s*=\s*resolve\(DRIZZLE_DIR,\s*["'][^"'/]+\.sql["']\)/);
});

