  assert.equal(sel.compare({ mode: FULL, atoms: [] }, new Set(SPECS), new Set([MUST]), discovered).ok, true);
  assert.equal(sel.compare({ mode: FULL, atoms: [] }, new Set(SPECS.slice(1)), new Set(), discovered).ok, false);
  assert.equal(sel.compare({ mode: FULL, atoms: [] }, new Set(), new Set(), new Set()).ok, false);
