// ---- verify --------------------------------------------------------------------------------

test("verify: every planned spec has a result, or the job goes red", () => {
  const discovered = new Set(SPECS);
  const plan = { mode: IMPACTED, atoms: ["test/a/one.spec.ts", MUST] };
  assert.equal(sel.compare(plan, new Set(plan.atoms), new Set(), discovered).ok, true);
  const short = sel.compare(plan, new Set(["test/a/one.spec.ts"]), new Set(), discovered);
  assert.equal(short.ok, false);
  assert.deepEqual(short.omitted, [MUST]);
  const extra = sel.compare(plan, new Set([...plan.atoms, "test/b/four.spec.ts"]), new Set(), discovered);
  assert.equal(extra.ok, false);
  // FULL compares with the whole discovered suite.
  assert.equal(sel.compare({ mode: FULL, atoms: [] }, new Set(SPECS), new Set([MUST]), discovered).ok, true);
  assert.equal(sel.compare({ mode: FULL, atoms: [] }, new Set(SPECS.slice(1)), new Set(), discovered).ok, false);
  assert.equal(sel.compare({ mode: FULL, atoms: [] }, new Set(), new Set(), new Set()).ok, false);
  // A failing spec is reported; the run step's Jest exit code keeps the job red.
  assert.deepEqual(sel.compare(plan, new Set(plan.atoms), new Set([MUST]), discovered).failing, [MUST]);
});

test("plan and verify end to end on files: IMPACTED, then a missing result fails verify", () => {
  const out = fs.mkdtempSync(path.join(os.tmpdir(), "rt1239-"));
  try {
    fs.writeFileSync(path.join(out, "guard.json"), JSON.stringify({ decision: "TIA_ELIGIBLE", reason: "ok", head: SHA, mustRun: [MUST], changed: [`${API}src/x.ts`] }));
    fs.writeFileSync(path.join(out, "discovered.txt"), `${SPECS.join("\n")}\n`);
    fs.writeFileSync(path.join(out, "selected.txt"), "test/a/one.spec.ts\ntest/a/two.spec.ts\n");
    fs.writeFileSync(path.join(out, "list-tests.rc"), "0\n");
    fs.writeFileSync(path.join(out, "probe.log"), probeText());
    fs.writeFileSync(path.join(out, "probe.rc"), "0\n");
    const log = console.log;
    console.log = () => {};
    let plan;
    const api = path.join(out, "api");
    for (const s of SPECS) {
      fs.mkdirSync(path.dirname(path.join(api, s)), { recursive: true });
      fs.writeFileSync(path.join(api, s), s === "test/b/three.spec.ts" ? 'import { readFileSync } from "node:fs";\n' : "\n");
    }
    try {
      // No api root: text readers unknown, so FULL.
      plan = sel.runPlan(out, { CIRCLE_SHA1: SHA, EXPECTED_SHA: SHA });
      assert.equal(plan.mode, FULL);
      plan = sel.runPlan(out, { CIRCLE_SHA1: SHA, EXPECTED_SHA: SHA }, api);
    } finally {
      console.log = log;
    }
    assert.equal(plan.mode, IMPACTED, plan.reasons.join("; "));
    assert.equal(fs.readFileSync(path.join(out, "canary-atoms.txt"), "utf8"), `test/a/one.spec.ts\ntest/a/two.spec.ts\ntest/b/three.spec.ts\n${MUST}\n`);
    const junit = path.join(out, "junit");
    fs.mkdirSync(junit);
    const suite = (f, fail = 0) => `<testsuite name="${f}" file="${f}" tests="1" failures="${fail}"></testsuite>`;
    fs.writeFileSync(path.join(junit, "r.xml"), `<testsuites>${suite("test/a/one.spec.ts")}${suite("test/a/two.spec.ts", 1)}${suite("test/b/three.spec.ts")}</testsuites>`);
    console.log = () => {};
    let report;
    try {
      report = sel.runVerify(out, junit, "");
    } finally {
      console.log = log;
    }
    assert.equal(report.ok, false);
    assert.deepEqual(report.omitted, [MUST]);
    assert.deepEqual(report.failing, ["test/a/two.spec.ts"]);
    // Same SHA but not the pinned one: FULL, and an empty atoms file.
    console.log = () => {};
    try {
      plan = sel.runPlan(out, { CIRCLE_SHA1: SHA, EXPECTED_SHA: "" }, api);
    } finally {
      console.log = log;
    }
    assert.equal(plan.mode, FULL);
    assert.equal(fs.readFileSync(path.join(out, "canary-atoms.txt"), "utf8"), "");
  } finally {
    fs.rmSync(out, { recursive: true, force: true });
  }
});

